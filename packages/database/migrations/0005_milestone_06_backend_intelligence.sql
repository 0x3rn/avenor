-- Milestone 06: Backend and Database Intelligence — Canonical Backend Metrics & Passive Security Posture Observations

CREATE TABLE IF NOT EXISTS backend_security_posture_observations (
  id TEXT PRIMARY KEY,
  organization_id TEXT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  project_id TEXT REFERENCES logical_projects(id) ON DELETE SET NULL,
  environment_id TEXT REFERENCES project_environments(id) ON DELETE SET NULL,
  provider_connection_id TEXT NOT NULL REFERENCES provider_connections(id) ON DELETE CASCADE,
  connected_resource_id TEXT NOT NULL REFERENCES connected_resources(id) ON DELETE CASCADE,
  provider_key TEXT NOT NULL CHECK (
    provider_key IN ('neon', 'supabase', 'firebase-monitoring')
  ),
  indicator_key TEXT NOT NULL,
  category TEXT NOT NULL CHECK (
    category IN (
      'ENCRYPTION_AND_TRANSPORT',
      'ACCESS_AND_NETWORK',
      'AUTHENTICATION_POSTURE',
      'DATA_PROTECTION_AND_RLS',
      'RULES_AND_POLICY_TELEMETRY',
      'AUDIT_AND_OPERATIONS'
    )
  ),
  title TEXT NOT NULL,
  status TEXT NOT NULL CHECK (
    status IN (
      'CONFIGURED',
      'NOT_CONFIGURED',
      'WARNING',
      'UNKNOWN',
      'NOT_VERIFIED',
      'UNAVAILABLE',
      'INSUFFICIENT_PERMISSION'
    )
  ),
  summary TEXT NOT NULL,
  qualification_note TEXT NOT NULL,
  sanitized_evidence JSONB NOT NULL DEFAULT '{}'::jsonb,
  observed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_backend_posture_resource_indicator UNIQUE (
    workspace_id,
    connected_resource_id,
    indicator_key
  )
);

CREATE INDEX IF NOT EXISTS idx_backend_posture_workspace_provider
  ON backend_security_posture_observations(workspace_id, provider_key, status);

CREATE INDEX IF NOT EXISTS idx_backend_posture_project_observed
  ON backend_security_posture_observations(project_id, observed_at DESC);

